using System;
using System.Collections.Generic;
using Haru.Annotations;
using Haru.Forms.Appearance;
using Haru.Graphics;
using Haru.Objects;
using Haru.Types;
using Haru.Xref;

namespace Haru.Forms
{
    /// <summary>
    /// Widget annotation for PDF form fields.
    /// Represents the visual appearance and placement of a form field on a page.
    /// </summary>
    public class HpdfWidgetAnnotation : HpdfAnnotation
    {
        private static readonly float[] DefaultBorderColor = { 0f, 0f, 0f };

        private readonly List<(HpdfStreamObject Stream, Action<HpdfAppearanceCanvas, float, float> Draw)> _appearanceStreams = new();
        private float[]? _borderColor;
        private float[]? _backgroundColor;
        private int _rotation;
        private string? _caption;
        private bool _characteristicsSet;

        /// <summary>
        /// Creates a new widget annotation.
        /// </summary>
        /// <param name="xref">The cross-reference table.</param>
        /// <param name="rect">The widget rectangle on the page.</param>
        public HpdfWidgetAnnotation(HpdfXref xref, HpdfRect rect)
            : base(xref, HpdfAnnotationType.Widget, rect)
        {
            // Set annotation flags: Print (bit 2 = 4) makes the widget visible/printable
            _dict.Add("F", new HpdfNumber(4));
        }

        /// <summary>
        /// Sets the parent field for this widget.
        /// </summary>
        /// <param name="field">The parent field.</param>
        public void SetParent(HpdfField field)
        {
            if (field is null)
                throw new HpdfException(HpdfErrorCode.InvalidParameter, "Field cannot be null");

            _dict.Add("Parent", field.Dict);
        }

        /// <summary>
        /// Sets the page reference for this widget.
        /// </summary>
        /// <param name="page">The page dictionary.</param>
        public void SetPage(HpdfDict page)
        {
            if (page is null)
                throw new HpdfException(HpdfErrorCode.InvalidParameter, "Page cannot be null");

            _dict.Add("P", page);
        }

        /// <summary>
        /// Sets the appearance state for this widget.
        /// </summary>
        /// <param name="state">The appearance state name (e.g., "Yes", "Off").</param>
        public void SetAppearanceState(string state)
        {
            if (string.IsNullOrEmpty(state))
                throw new HpdfException(HpdfErrorCode.InvalidParameter, "State cannot be null or empty");

            _dict.Remove("AS");
            _dict.Add("AS", new HpdfName(state));
        }

        /// <summary>
        /// Sets the highlighting mode for the widget.
        /// </summary>
        /// <param name="mode">The highlighting mode.</param>
        public void SetHighlightMode(HpdfHighlightMode mode)
        {
            string modeName = mode switch
            {
                HpdfHighlightMode.NoHighlight => "N",
                HpdfHighlightMode.InvertBox => "I",
                HpdfHighlightMode.InvertBorder => "O",
                HpdfHighlightMode.DownAppearance => "P",
                _ => "I"
            };

            _dict.Remove("H");
            _dict.Add("H", new HpdfName(modeName));
        }

        /// <summary>
        /// Sets appearance characteristics dictionary (/MK) for the widget.
        /// Appearance streams generated by this library for the widget (checkbox, radio button
        /// and signature frames) are redrawn with the new colors.
        /// </summary>
        /// <param name="borderColor">The border color (RGB, each component 0-1), or null for no border.</param>
        /// <param name="backgroundColor">The background color (RGB, each component 0-1), or null for no background.</param>
        /// <param name="rotation">The rotation angle (0, 90, 180, or 270).</param>
        public void SetAppearanceCharacteristics(float[]? borderColor = null, float[]? backgroundColor = null, int rotation = 0)
        {
            if (rotation != 0 && rotation != 90 && rotation != 180 && rotation != 270)
                throw new HpdfException(HpdfErrorCode.InvalidParameter, "Rotation must be 0, 90, 180, or 270");

            _borderColor = borderColor is { Length: 3 } ? borderColor : null;
            _backgroundColor = backgroundColor is { Length: 3 } ? backgroundColor : null;
            _rotation = rotation;
            _characteristicsSet = true;

            UpdateAppearance();
        }

        /// <summary>
        /// Creates appearance dictionary for button widgets (checkbox/radio) with actual drawing commands.
        /// Each state draws the frame (border and background of the appearance characteristics;
        /// a black border unless <see cref="SetAppearanceCharacteristics"/> was called) and its mark.
        /// </summary>
        /// <param name="elementType">The type of button element (checkbox or radio button).</param>
        /// <param name="onStateName">The "on" state name (e.g., "Yes" for checkbox, "Male" for radio).</param>
        /// <param name="offStateName">The "off" state name (typically "Off").</param>
        public void SetButtonAppearances(ButtonElementType elementType, string onStateName = "Yes", string offStateName = "Off")
        {
            IElementAppearance generator = HpdfAppearanceFactory.CreateAppearance(elementType);

            _appearanceStreams.Clear();
            _caption = generator.Caption;

            var normal = new HpdfDict();
            normal.Add(onStateName, CreateAppearanceStream((canvas, width, height) =>
            {
                generator.DrawFrame(canvas, width, height, _borderColor, _backgroundColor);
                generator.GenerateOnStateAppearance(canvas, width, height);
            }));
            normal.Add(offStateName, CreateAppearanceStream((canvas, width, height) =>
            {
                generator.DrawFrame(canvas, width, height, _borderColor, _backgroundColor);
                generator.GenerateOffStateAppearance(canvas, width, height);
            }));

            SetNormalAppearance(normal);
        }

        /// <summary>
        /// Creates an appearance for a widget that shows only its frame: the border and background
        /// of the appearance characteristics (a black border unless
        /// <see cref="SetAppearanceCharacteristics"/> was called). Used for unsigned signature fields,
        /// which would otherwise be invisible in viewers that do not draw such fields themselves.
        /// </summary>
        public void SetFrameAppearance()
        {
            _appearanceStreams.Clear();
            _caption = null;

            SetNormalAppearance(CreateAppearanceStream((canvas, width, height) =>
                HpdfWidgetFrame.DrawBox(canvas, width, height, _borderColor, _backgroundColor)));
        }

        /// <summary>
        /// Creates a Form XObject for an appearance stream of the widget's size.
        /// </summary>
        /// <param name="draw">Draws the content on the given canvas for the given width and height.</param>
        private HpdfStreamObject CreateAppearanceStream(Action<HpdfAppearanceCanvas, float, float> draw)
        {
            HpdfRect rect = GetRect();

            // Appearance streams MUST be Form XObjects per PDF spec
            var stream = new HpdfStreamObject();
            stream.Add("Type", new HpdfName("XObject"));
            stream.Add("Subtype", new HpdfName("Form"));
            stream.Add("BBox", CreateBBoxArray(0, 0, rect.Right - rect.Left, rect.Top - rect.Bottom));
            stream.Add("Resources", new HpdfDict());
            _xref.Add(stream);

            _appearanceStreams.Add((stream, draw));
            return stream;
        }

        /// <summary>
        /// Attaches the normal appearance (a stream, or a dictionary of state streams) and draws it.
        /// </summary>
        private void SetNormalAppearance(HpdfObject normal)
        {
            if (!_characteristicsSet)
                _borderColor = DefaultBorderColor;

            var ap = new HpdfDict();
            ap.Add("N", normal);
            _dict.Remove("AP");
            _dict.Add("AP", ap);

            UpdateAppearance();
        }

        /// <summary>
        /// Writes the appearance characteristics (/MK) and redraws the generated appearance streams,
        /// so both always describe the same border, background and mark.
        /// </summary>
        private void UpdateAppearance()
        {
            var mk = new HpdfDict();

            if (_borderColor != null)
                mk.Add("BC", CreateColorArray(_borderColor));

            if (_backgroundColor != null)
                mk.Add("BG", CreateColorArray(_backgroundColor));

            if (_rotation != 0)
                mk.Add("R", new HpdfNumber(_rotation));

            if (_caption != null)
                mk.Add("CA", new HpdfString(_caption));

            _dict.Remove("MK");
            if (mk.Count > 0)
                _dict.Add("MK", mk);

            HpdfRect rect = GetRect();
            foreach (var (stream, draw) in _appearanceStreams)
            {
                stream.ClearStream();
                draw(new HpdfAppearanceCanvas(stream), rect.Right - rect.Left, rect.Top - rect.Bottom);
            }
        }

        private static HpdfArray CreateColorArray(float[] color)
        {
            var array = new HpdfArray();
            foreach (float component in color)
                array.Add(new HpdfReal(component));
            return array;
        }

        /// <summary>
        /// Gets the rectangle of this widget annotation.
        /// </summary>
        /// <returns>The widget's rectangle.</returns>
        private HpdfRect GetRect()
        {
            // The Rect is stored in the annotation dictionary
            if (_dict.TryGetValue("Rect", out var rectObj) && rectObj is HpdfArray rectArray && rectArray.Count == 4)
            {
                float left = (rectArray[0] as HpdfNumber)?.Value ?? (rectArray[0] as HpdfReal)?.Value ?? 0;
                float bottom = (rectArray[1] as HpdfNumber)?.Value ?? (rectArray[1] as HpdfReal)?.Value ?? 0;
                float right = (rectArray[2] as HpdfNumber)?.Value ?? (rectArray[2] as HpdfReal)?.Value ?? 0;
                float top = (rectArray[3] as HpdfNumber)?.Value ?? (rectArray[3] as HpdfReal)?.Value ?? 0;

                return new HpdfRect(left, bottom, right, top);
            }

            // Default fallback
            return new HpdfRect(0, 0, 15, 15);
        }

        /// <summary>
        /// Creates a BBox (bounding box) array for Form XObjects.
        /// </summary>
        /// <param name="llx">Lower-left x coordinate.</param>
        /// <param name="lly">Lower-left y coordinate.</param>
        /// <param name="urx">Upper-right x coordinate.</param>
        /// <param name="ury">Upper-right y coordinate.</param>
        /// <returns>An HpdfArray representing the bounding box.</returns>
        private static HpdfArray CreateBBoxArray(float llx, float lly, float urx, float ury)
        {
            var bbox = new HpdfArray();
            bbox.Add(new HpdfReal(llx));
            bbox.Add(new HpdfReal(lly));
            bbox.Add(new HpdfReal(urx));
            bbox.Add(new HpdfReal(ury));
            return bbox;
        }
    }
}
