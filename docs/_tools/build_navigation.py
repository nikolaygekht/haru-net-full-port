"""
Builds docs/CONTENTS.md (table of contents) and docs/API_INDEX.md (alphabetical index) from the pages in docs/.

Run after adding, renaming or restructuring pages:

    python docs/_tools/build_navigation.py

The script reads only Markdown headings and the first paragraph of each page, so the generated files always match
the pages. Folders starting with "_" are not published by GitHub Pages, so this script stays out of the site.
"""

import io
import os
import re
import sys

DOCS = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
GENERATED = {"CONTENTS.md", "API_INDEX.md"}
NOTICE = "<!-- Generated by docs/_tools/build_navigation.py - do not edit by hand. -->"

# Sections of the table of contents: (title, folder or explicit file list, description)
SECTIONS = [
    ("Start Here", ["INDEX.md", "USAGE.md", "guides/GettingStarted.md", "STRUCTURE.md", "LICENSE.md"],
     "Overview, installation, a first PDF and the architecture of the library."),
    ("Guides", ["guides/FontsGuide.md", "guides/TextGuide.md", "guides/GraphicsGuide.md", "guides/ImagesGuide.md",
                "guides/FormsGuide.md", "guides/AnnotationsGuide.md", "guides/ThreeDGuide.md", "guides/OutlinesGuide.md",
                "guides/EncryptionGuide.md"],
     "Task-oriented tutorials with runnable examples."),
    ("Core Classes", "api/core", "Documents, pages, fonts, images and the document-level objects (namespace `Haru.Doc`, fonts in `Haru.Font`)."),
    ("Drawing and Text (Extension Methods)", "api/extensions", "The operations you call on a page."),
    ("Forms", "api/forms", "Interactive form fields and their widgets (namespaces `Haru.Forms`, `Haru.Forms.Appearance`)."),
    ("Annotations", "api/annotations", "Notes, links, markup annotations (review comments), pop-ups, file attachments and 3D annotations (namespace `Haru.Annotations`)."),
    ("3D Models", "api/threed", "3D models, views, nodes and measurements shown by 3D annotations (namespace `Haru.ThreeD`)."),
    ("Types and Enumerations", "api/types", "Value types, page sizes, enums and constants (namespace `Haru.Types`, page sizes in `Haru.Doc`)."),
]

# Within a folder, these pages come first (the rest follow alphabetically)
FIRST = {
    "api/core": ["HpdfDocument.md", "HpdfPage.md", "HpdfFont.md", "HpdfImage.md"],
    "api/extensions": ["HpdfPageGraphics.md", "HpdfPageShapes.md", "HpdfPageText.md"],
    "api/forms": ["HpdfAcroForm.md", "HpdfField.md", "HpdfTextField.md", "HpdfCheckbox.md", "HpdfRadioButton.md",
                  "HpdfChoice.md", "HpdfSignature.md", "HpdfWidgetAnnotation.md"],
    "api/annotations": ["HpdfAnnotation.md", "HpdfLinkAnnotation.md", "HpdfMarkupAnnotation.md", "HpdfTextAnnotation.md",
                        "HpdfGeometricAnnotation.md", "HpdfShapeAnnotation.md", "HpdfLineAnnotation.md",
                        "HpdfPolygonalAnnotation.md", "HpdfPolygonAnnotation.md", "HpdfPolyLineAnnotation.md",
                        "HpdfInkAnnotation.md", "HpdfTextMarkupAnnotation.md", "HpdfCaretAnnotation.md",
                        "HpdfFreeTextAnnotation.md", "HpdfStampAnnotation.md", "HpdfRedactAnnotation.md",
                        "HpdfFileAttachmentAnnotation.md", "HpdfPopupAnnotation.md", "Hpdf3DAnnotation.md",
                        "HpdfProjectionAnnotation.md"],
    "api/threed": ["Hpdf3DModel.md", "Hpdf3DView.md", "Hpdf3DNode.md", "Hpdf3DMeasure.md", "Hpdf3DCommentNote.md",
                   "Hpdf3DPerpendicularMeasure.md"],
    "api/types": ["HpdfRect.md", "HpdfBox.md", "HpdfPoint.md", "HpdfTransMatrix.md", "HpdfRgbColor.md",
                  "HpdfCmykColor.md", "HpdfDashMode.md", "HpdfPageSize.md", "HpdfPageDirection.md", "HpdfPageSizes.md"],
}

# Descriptions for pages whose first paragraph does not describe the page
DESCRIPTIONS = {
    "USAGE.md": "Installing the package, the basic concepts and the most common tasks in short examples.",
}

MEMBER_SECTION = re.compile(r"(propert|method|constructor|constant|operator|field)", re.I)
# Level-2 sections of API pages whose level-3 headings are not members
NON_MEMBER_SECTION = re.compile(r"(overview|purpose|example|best practice|see also|related|getting|standard fonts|"
                                r"loading|values|where it is used|remarks|limitation|known|usage|summary|types$)", re.I)
CISE_MEMBER = re.compile(r"^(Property|Method|Constructor|Operator|Field|Constant|Event):\s*\*?([A-Za-z_][A-Za-z0-9_]*)")
PLAIN_MEMBER = re.compile(r"^([A-Z][A-Za-z0-9_]*)(\s*\(.*\))?$")
TITLE = re.compile(r"^#\s+(.*?)\s*$")


def read(path):
    with io.open(path, encoding="utf-8") as f:
        return f.read()


def strip_code(text):
    return re.sub(r"```.*?```", "", text, flags=re.S)


def slugger():
    """GitHub / kramdown style heading ids, with -1, -2 ... for repeated headings on one page."""
    seen = {}

    def slug(heading):
        s = heading.strip().lower()
        s = re.sub(r"[^\w\- ]", "", s).replace(" ", "-")
        if s in seen:
            seen[s] += 1
            return "%s-%d" % (s, seen[s])
        seen[s] = 0
        return s
    return slug


def headings(text):
    """(level, text, anchor) for every heading outside code blocks."""
    slug = slugger()
    result = []
    for line in strip_code(text).splitlines():
        m = re.match(r"^(#{1,6})\s+(.*?)\s*$", line)
        if m:
            result.append((len(m.group(1)), m.group(2), slug(m.group(2))))
    return result


def title_of(text, rel):
    for line in text.splitlines():
        m = TITLE.match(line)
        if m:
            return re.sub(r"\s*[:\-]\s*$", "", m.group(1))
    return os.path.splitext(os.path.basename(rel))[0]


def summary_of(text):
    """The first sentence of the first plain paragraph of the page."""
    for block in re.split(r"\n\s*\n", strip_code(text)):
        block = block.strip()
        if not block or block[0] in "#|-*>[<!" or block.startswith("**") or block.startswith("---"):
            continue
        sentence = re.split(r"(?<=[.!?])\s", " ".join(block.split()), maxsplit=1)[0]
        sentence = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", sentence)
        if len(sentence) > 160 and ": " in sentence:
            # "This guide shows how to ...: a, b, c" -> the part before the list
            sentence = sentence.split(": ", 1)[0].rstrip(",;") + "."
        if len(sentence) > 200:
            sentence = sentence[:200].rsplit(" ", 1)[0].rstrip(",;:") + "..."
        return sentence
    return ""


def pages_of(folder):
    names = sorted(f for f in os.listdir(os.path.join(DOCS, folder)) if f.endswith(".md"))
    first = [n for n in FIRST.get(folder, []) if n in names]
    return [folder + "/" + n for n in first + [n for n in names if n not in first]]


def all_pages():
    pages = []
    for root, dirs, files in os.walk(DOCS):
        dirs[:] = [d for d in dirs if not d.startswith(("_", "."))]
        for f in files:
            if f.endswith(".md"):
                rel = os.path.relpath(os.path.join(root, f), DOCS).replace("\\", "/")
                if rel not in GENERATED:
                    pages.append(rel)
    return sorted(pages)


def build_contents():
    out = ["# Table of Contents", "", NOTICE, "",
           "[← Back to Documentation Index](INDEX.md) · [Alphabetical Index](API_INDEX.md)", ""]
    listed = set()
    for title, source, description in SECTIONS:
        files = source if isinstance(source, list) else pages_of(source)
        out += ["## " + title, "", description, ""]
        for rel in files:
            path = os.path.join(DOCS, rel)
            if not os.path.isfile(path):
                continue
            text = read(path)
            summary = DESCRIPTIONS.get(rel) or summary_of(text)
            line = "- [%s](%s)" % (title_of(text, rel), rel)
            out.append(line + (" - " + summary if summary else ""))
            listed.add(rel)
        out.append("")

    missing = [p for p in all_pages() if p not in listed]
    if missing:
        out += ["## Other Pages", ""]
        out += ["- [%s](%s)" % (title_of(read(os.path.join(DOCS, p)), p), p) for p in missing]
        out.append("")

    out += ["---", "", "[← Back to Documentation Index](INDEX.md)", ""]
    return "\n".join(out)


def type_name(title):
    return re.split(r"\s+", title.strip())[0]


def build_index():
    types = []      # (name, kind, rel)
    members = []    # (member, type, kind, rel, anchor)
    topics = []     # (topic, page title, rel, anchor)

    # Headings that name a type (e.g. "### HpdfExtGState" on another type's page) are not members
    type_names = {type_name(title_of(read(os.path.join(DOCS, p)), p)) for p in all_pages() if p.startswith("api/")}

    for rel in all_pages():
        text = read(os.path.join(DOCS, rel))
        heads = headings(text)
        title = title_of(text, rel)

        if rel.startswith("guides/"):
            section = ""
            for level, head, anchor in heads:
                if level == 2:
                    section = head
                # Skip navigation sections, numbered steps and the individual items of pitfall lists
                if level not in (2, 3) or re.match(r"^\d", head):
                    continue
                if head.lower() in ("see also", "overview", "contents", "summary", "complete example", "next steps"):
                    continue
                if level == 3 and re.search(r"pitfall|mistake|troubleshoot", section, re.I):
                    continue
                topics.append((head, title, rel, anchor))
            continue

        if not rel.startswith("api/"):
            continue

        name = type_name(title)
        kind_match = re.search(r"\b(Class|Struct|Enum|Interface)\b", title)
        types.append((name, kind_match.group(1).lower() if kind_match else "page", rel))

        section = ""
        for level, head, anchor in heads:
            if level == 2:
                section = head
                continue
            m = CISE_MEMBER.match(head)
            if m:
                members.append((m.group(2), name, m.group(1).lower(), rel, anchor))
                continue
            if level == 3 and not NON_MEMBER_SECTION.search(section):
                m = PLAIN_MEMBER.match(head)
                if m and (m.group(1) not in type_names or re.search("constructor", section, re.I)):
                    if re.search("constructor", section, re.I):
                        kind = "constructor"
                    elif re.search("propert", section, re.I) and not m.group(2):
                        kind = "property"
                    elif re.search("constant", section, re.I):
                        kind = "constant"
                    else:
                        kind = "method"
                    members.append((m.group(1), name, kind, rel, anchor))

    # One entry per (member, type): overloads link to the first description
    unique = {}
    for member, owner, kind, rel, anchor in members:
        unique.setdefault((member, owner), (member, owner, kind, rel, anchor))

    entries = [(n, "%s (%s)" % (n, k), rel, "") for n, k, rel in types]
    entries += [(m, "%s - %s of %s" % (m, k, owner), rel, a) for m, owner, k, rel, a in unique.values()]
    entries.sort(key=lambda e: (e[0].lower(), e[1].lower()))

    out = ["# Alphabetical Index", "", NOTICE, "",
           "[← Back to Documentation Index](INDEX.md) · [Table of Contents](CONTENTS.md)", "",
           "## Topics", "", "Sections of the guides, by subject.", ""]
    for topic, page, rel, anchor in sorted(topics, key=lambda t: t[0].lower()):
        out.append("- [%s](%s#%s) - %s" % (topic, rel, anchor, page))

    out += ["", "## Types and Members", "",
            "Every documented type, property, method and constructor. Overloads link to their first description.", ""]
    letters = sorted({e[0][0].upper() for e in entries})
    out.append(" · ".join("[%s](#%s)" % (l, l.lower()) for l in letters))
    current = None
    for name, label, rel, anchor in entries:
        letter = name[0].upper()
        if letter != current:
            out += ["", "### " + letter, ""]
            current = letter
        out.append("- [%s](%s%s)" % (label, rel, "#" + anchor if anchor else ""))

    out += ["", "---", "", "[← Back to Documentation Index](INDEX.md)", ""]
    return "\n".join(out)


def write(name, content):
    with io.open(os.path.join(DOCS, name), "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print("written", name)


if __name__ == "__main__":
    write("CONTENTS.md", build_contents())
    write("API_INDEX.md", build_index())
    sys.exit(0)
